// Постер события: показать афишу целиком, а не её середину.
//
// Афиши приходят от площадок какими есть. Instagram даёт квадрат 1:1,
// обложка Facebook — 16:9, сторис — 9:16, дизайнер клуба рисует 3:4 или
// вообще 2:3. Мы же рисовали их все в рамке 4:5 через object-fit: cover,
// то есть обрезали до заполнения.
//
// Обрезка съедала ровно то, ради чего афишу и смотрят. У горизонтальной
// обложки уходили левый и правый края — там имена артистов и время.
// У сторис срезались верх и низ — там дата и «вход свободный». Гость
// видел красивый кусок картинки без единого факта.
//
// Лечится contain’ом: афиша вписывается целиком, а пустота по бокам
// заполняется размытой копией её же. Приём стандартный для медиа
// неизвестных пропорций — так делают все плееры и галереи, — и он
// честнее любой обрезки: ничего не теряется, а рамка остаётся ровной,
// чтобы сетка карточек не прыгала.
import { useState } from "react";

export const PosterImg = ({
  src,
  alt = "",
  ratio = "4/5",
  radius,
}: {
  src: string;
  alt?: string;
  /** Рамка карточки. Одинаковая у всех карточек ленты — иначе сетка
   *  скачет; сама афиша внутри неё живёт в своих пропорциях. */
  ratio?: string;
  radius?: number;
}) => {
  const [failed, setFailed] = useState(false);
  return (
    <span
      style={{
        position: "relative",
        display: "block",
        width: "100%",
        aspectRatio: ratio,
        overflow: "hidden",
        background: "#101116",
        borderRadius: radius,
      }}
    >
      {!failed ? (
        <>
          {/* Подложка: та же картинка, растянутая и размытая. Она не
              несёт информации — только закрывает поля, чтобы афиша не
              висела в чёрной пустоте. aria-hidden: экранному диктору
              она не нужна, это второй экземпляр той же картинки. */}
          <img
            src={src}
            alt=""
            aria-hidden
            loading="lazy"
            style={{
              position: "absolute",
              inset: 0,
              width: "100%",
              height: "100%",
              objectFit: "cover",
              filter: "blur(22px) saturate(1.25) brightness(.55)",
              // Лёгкий разгон: размытие съедает края, и без него по
              // периметру видна светлая кайма от краёв исходника.
              transform: "scale(1.15)",
            }}
            onError={() => setFailed(true)}
          />
          <img
            src={src}
            alt={alt}
            loading="lazy"
            style={{
              position: "relative",
              display: "block",
              width: "100%",
              height: "100%",
              objectFit: "contain",
            }}
            onError={() => setFailed(true)}
          />
        </>
      ) : null}
    </span>
  );
};
