// Дневные задачи: что пора запускать прямо сейчас.
//
// Раньше у каждой был собственный крон. Бесплатный тариф Workers даёт
// пять триггеров на весь аккаунт, а задач у нас семь — и выкатка
// 13.10.2026 упала ровно на этом: код уехал, а расписание Cloudflare
// принял частично («Trigger configuration was only partially updated»,
// код 10072). Какие именно задачи остались без расписания, снаружи не
// видно вовсе — худший вид поломки.
//
// Поэтому дневные задачи висят на тике сторожа, который и так ходит
// каждые пятнадцать минут. В Cloudflare это один триггер, а задач на
// нём сколько угодно.
//
// Побочно вышло надёжнее, чем было. Крон «ровно в 08:00» — это одна
// попытка в сутки: не сработала, и задача пропала до завтра. Здесь
// каждая задача помнит, выполнялась ли она сегодня, и её подхватит
// первый же тик после назначенного часа. Пропущенный тик стоит
// пятнадцати минут задержки, а не суток молчания.
//
// Модуль чистый: ни сети, ни хранилища, ни nitro. Правило «час настал,
// сегодня ещё не бегало» проверяется тестом, а не наблюдением за
// продом в течение суток.

export type DailyJob = {
  /** Час по Пхукету, с которого задачу можно запускать. */
  hour: number;
  route: string;
  what: string;
};

/** Часы те же, что были у отдельных кронов: люди к ним привыкли. */
export const DAILY_JOBS: DailyJob[] = [
  { hour: 8, route: "/api/fill-digest", what: "очередь наполнения на смену" },
  { hour: 9, route: "/api/villa-check", what: "сверка цен вилл Private" },
  { hour: 11, route: "/api/bro-learn", what: "BRO учит новые темы" },
  { hour: 17, route: "/api/community-digest", what: "дайджест вечера" },
  { hour: 20, route: "/api/sprint-report", what: "вечерний отчёт спринта" },
];

/** Сутки считаем по месту, где живёт команда. По UTC «утренняя сводка»
 *  пришла бы накануне вечером. */
export const bkkDate = (now = Date.now()): string =>
  new Date(now + 7 * 3600e3).toISOString().slice(0, 10);

export const bkkHour = (now = Date.now()): number =>
  new Date(now + 7 * 3600e3).getUTCHours();

/** Что пора запускать: час настал, а сегодня ещё не бегало. */
export const dueJobs = (ranToday: ReadonlySet<string>, now = Date.now()): DailyJob[] =>
  DAILY_JOBS.filter((j) => bkkHour(now) >= j.hour && !ranToday.has(j.route));

export const ranKey = (route: string, now = Date.now()) =>
  `cronran:${route}:${bkkDate(now)}`;
