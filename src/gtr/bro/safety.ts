/** Разбор реплики. Возвращает null, если разговор обычный. */
export const safetyOf = (raw: string): SafetyHit | null => {
  const t = raw.trim().slice(0, 300);
  if (t.length < 3) return null;
  for (const [kind, re] of RE) {
    if (re.test(t)) return { kind, ...REPLY[kind] };
  }
  return null;
};
