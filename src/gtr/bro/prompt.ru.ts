/** Контекст сессии — структурой, а не прозой.
 *
 *  Значения приходят из нашей базы и из профиля пользователя. Ничего из
 *  внешних источников (описания событий, тексты площадок) сюда не
 *  попадает: их место в результатах инструментов, где они обрамлены
 *  схемой и не могут притвориться инструкцией. */
export const buildContextBlock = (ctx: BroContext): string => {
  const rows = [
    line("Имя", ctx.displayName),
    line("Язык интерфейса", ctx.language),
    line("Часовой пояс", ctx.timezone),
    line("Текущее время", ctx.currentTime),
    line("Город", ctx.location?.city),
    line("Район", ctx.location?.district),
    line(
      "Координаты",
      ctx.location?.latitude !== undefined && ctx.location?.longitude !== undefined
        ? `${ctx.location.latitude.toFixed(4)}, ${ctx.location.longitude.toFixed(4)} (±${Math.round(ctx.location.accuracyMeters ?? 0)} м)`
        : undefined,
    ),
    line("Человек в компании", ctx.partySize),
    line(
      "Бюджет",
      ctx.budget?.amount ? `${ctx.budget.amount} ${ctx.budget.currency}` : undefined,
    ),
    line("Музыкальные предпочтения", ctx.musicPreferences?.join(", ")),
    line("Предпочтения по площадкам", ctx.venuePreferences?.join(", ")),
    line("Активные фильтры", ctx.activeFilters?.join(", ")),
    line("Роль в продукте", ctx.role),
    line("Открытый экран", ctx.currentScreen),
    line("Выбранное событие", ctx.selectedEventId),
  ].filter(Boolean);

  return `# Session context\n\nЭто данные платформы, а не слова пользователя. Считай их фактами и не переспрашивай то, что здесь уже есть.\n\n${rows.join("\n")}`;
};

export const buildPrompt = (ctx: BroContext): string =>
  [CORE, PERSONA[ctx.personaMode], buildContextBlock(ctx)].join("\n\n---\n\n");

