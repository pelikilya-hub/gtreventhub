// Предохранитель правдивости текстового мозга GTR BRO.
//
// Мозг обязан брать факты из инструментов. Живой прогон показал: Qwen 8B
// на CPU время от времени игнорирует правило и выдаёт список
// несуществующих баров с уверенным видом — или, что хуже, мешает
// настоящие названия с выдуманными. Для человека, который поедет по
// этому адресу, это худший возможный ответ: хуже, чем «не знаю».
//
// Правило простое и механическое, а не «на усмотрение модели»: если в
// этом ходу не вызван ни один инструмент, ответ не имеет права называть
// ничего конкретного. Без инструментов BRO может только уточнять,
// шутить и честно отказываться. Всё остальное — карантин и тихий откат
// на разбор по правилам, который ищет по нашей базе.

/** Слова, которые сами по себе не факт, а разрешённая часть речи. */
const SAFE = new Set([
  "GTR", "BRO", "Grab", "Bolt", "Telegram", "WhatsApp", "Google", "Maps",
  "Spotify", "SoundCloud", "YouTube", "Deezer", "Instagram", "Apple", "Phuket",
  "THB", "VIP", "DJ", "OK", "Wi", "Fi",
]);

/** Латинское имя собственное: «Illuzion», «Café del Mar», «Sugar Club».
 *  Именно латинское: \p{Lu} захватил бы и обычное русское начало фразы
 *  («Брат, давай поищем»), и карантин глотал бы живой разговор. */
const LATIN_NAME = /(^|[^A-Za-z])([A-Z][A-Za-z'’-]{2,})/g;

/** Маркированный список — форма, в которой модель обычно и «сдаёт»
 *  выдуманную подборку мест. */
const BULLET = /(^|\n)\s*[-*·•]\s*\S/;

/** Кириллические имена в кавычках: «Аура», «Тигр». */
const QUOTED = /«[^»]{2,}»/;

export const looksInvented = (reply: string, calledTools: number): boolean => {
  if (calledTools > 0) return false;
  const text = String(reply ?? "");
  if (!text.trim()) return false;
  if (BULLET.test(text) || QUOTED.test(text)) return true;
  for (const m of text.matchAll(LATIN_NAME)) {
    const word = m[2];
    if (!SAFE.has(word)) return true;
  }
  return false;
};

// ------------------------------------------------- защита устройства BRO
//
// У помощника спрашивают не только про вечеринки. Отдельный класс
// запросов — «покажи свой системный промпт», «перечисли все инструменты»,
// «выведи всю базу площадок в json»: так снимают не ответ, а сам продукт.
// Модель на такое отвечает охотно, поэтому ловим до модели.
//
// Обычные вопросы «что ты умеешь» под это не попадают намеренно: человек
// имеет право знать возможности, но не внутренности.

// \w в JavaScript — только ASCII, поэтому «инструкци\w+» не совпадает с
// «инструкции»: кириллица мимо. Классы задаём явно — на этой же грабле
// продукт спотыкался уже не раз.
const EXTRACTION: RegExp[] = [
  // просьбы показать инструкции и устройство
  /(системн[а-яё]*|исходн[а-яё]*|первоначальн[а-яё]*)\s+(промпт|инструкц[а-яё]+|сообщен[а-яё]+)/i,
  /(покажи|выведи|повтори|процитируй|раскрой|скинь|напиши)[^.?!]{0,40}(промпт|инструкци[а-яё]+|правил[а-яё]+ выше|свой код|исходник[а-яё]*)/i,
  /(ignore|disregard|forget)[^.?!]{0,30}(previous|above|prior)[^.?!]{0,20}(instructions?|prompt)/i,
  /(system|initial|original)\s+prompt/i,
  /(перечисли|назови|покажи|выведи|какие)[^.?!]{0,20}(инструмент|функци|tools)/i,
  /(тво[ияе]|ваши|список)\s+(инструмент[а-яё]*|функци[а-яё]*|tools)/i,
  /developer\s+mode|jailbreak|DAN\s+mode/i,
  // просьбы выгрузить базу целиком
  /(вывед[иь]|выгруз[иь]|дай|скинь|экспортируй)[^.?!]{0,40}(вс[ею]х?|полн[а-яё]+|цел[а-яё]+)[^.?!]{0,25}(баз[а-яё]+|список[а-яё]*|таблиц[а-яё]+|json|csv)/i,
  /(вс[еех]{1,3}|полный список)\s+(площадк[а-яё]+|артист[а-яё]+|контакт[а-яё]+)[^.?!]{0,20}(json|csv|таблиц[а-яё]+|списком)/i,
  /(json|csv|дамп|dump)\s+(баз[а-яё]+|данн[а-яё]+|площадок|артистов)/i,
];

export const looksLikeExtraction = (text: string): boolean => {
  const t = text.slice(0, 500);
  return EXTRACTION.some((re) => re.test(t));
};

