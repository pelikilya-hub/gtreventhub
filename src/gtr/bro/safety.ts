// Четыре разговора, где ошибка помощника стоит здоровья.
//
// Вещества, пьяная езда, скорая, несовершеннолетние в клубе. Здесь
// сознательно нет нейросети: эти ответы обязаны быть одинаковыми в
// любую ночь, при любом состоянии человека и при любом провайдере
// голоса. Правила ловят намерение до модели и отвечают заготовкой.
//
// Тон: BRO остаётся собой — коротко, без морали и лекций. Отказ звучит
// как «этим не занимаюсь», а не как выговор, и всегда даёт замену.
// Человеку, которому отказали с презрением, второй раз не помогут.
//
// Кириллица: \b в JavaScript опирается на ASCII, поэтому границы слов
// задаём явно — на этой грабле продукт стоял восемь раз.

export type SafetyKind = "substances" | "drunk_drive" | "medical" | "minor";

export type SafetyHit = { kind: SafetyKind; reply: string; hint?: string };

/** Телефоны Таиланда. Единые по стране, работают с любого номера,
 *  включая иностранную SIM и телефон без баланса. */
export const TH_EMERGENCY = {
  ambulance: "1669",
  police: "191",
  tourist: "1155",
} as const;

const RE: [SafetyKind, RegExp][] = [
  // Скорая идёт первой: «передоз» содержит и вещества, и угрозу жизни,
  // и в этом случае важнее вызвать помощь, чем отказать в покупке.
  [
    "medical",
    /передоз|овердоз|overdose|без сознан|потер[а-яё]* сознан|не дыш|тяжело дыш|задыха|судорог|не приход[а-яё]* в себя|скор[а-яё]* помощ|ambulance|срочн[а-яё]* помощ|плохо с сердц|приступ|истека[а-яё]* кровь/i,
  ],
  [
    "substances",
    // Два пути: «глагол → предмет» и «предмет → глагол». Отдельно слова,
    // которые в ночном разговоре ничего другого не значат.
    /(куп[а-яё]*|найд[а-яё]*|где взять|нужен|нужны|нужно|достан[а-яё]*|организу[а-яё]*|привез[а-яё]*)[^.?!]{0,25}(стаф|стафф|вещест|наркот|травк|шишк|мдма|mdma|экстази|кокаин|кокс|амфетамин|меф|соль|лсд|марихуан|weed|ganja|cocaine|drugs)|(стаф|вещест|наркот)[^.?!]{0,20}(куп|найд|достан|привез|достав)|(^|[^а-яё])(дилер|барыг[а-яё]*|закладк[а-яё]*)([^а-яё]|$)/i,
  ],
  [
    "drunk_drive",
    /(выпил[а-яё]*|пьян[а-яё]*|бухой|под вещест|под кайфом|нетрезв[а-яё]*)[^.?!]{0,30}(поед|сяд|за рул[её]м|веду|вести|байк|скутер|машин|drive)|(поед|сяду|сам доед)[^.?!]{0,20}(пьян|выпивш|бухой)|(можно|можн)[^.?!]{0,15}(вести|ехать|сесть за рул)[^.?!]{0,30}(после|выпив|бокал|пив|коктейл)/i,
  ],
  [
    "minor",
    // Порядок слов в живой речи любой: «пустят, если семнадцать» и
    // «семнадцатилетнего пустят» — один и тот же вопрос.
    /(1[0-9]\s*лет|семнадцат[а-яё]*|шестнадцат[а-яё]*|пятнадцат[а-яё]*|несовершеннолетн[а-яё]*|подростк[а-яё]*|ребёнк[а-яё]*|ребенк[а-яё]*|дет[а-яё]+)[^.?!]{0,40}(клуб|бар|вечеринк|пуст[яи]т|прон[её]с|фейс.?контрол)|(пуст[яи]т|взять|провести|пройти|пройд[её]м)[^.?!]{0,40}(1[0-9]\s*лет|семнадцат[а-яё]*|шестнадцат[а-яё]*|несовершеннолетн[а-яё]*|подростк[а-яё]*|ребёнк[а-яё]*|ребенк[а-яё]*)|обойти проверку возраст|как пройти фейс.?контрол[а-яё]* без/i,
  ],
];

