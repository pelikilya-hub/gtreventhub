// Автопереключатель голосовых полос GTR BRO.
//
// Полос две. Премиальная — живой сокет к голосовому провайдеру
// (Gemini Live или Realtime): естественный голос, но единственная
// точка отказа — любой сбой их облака глушит разговор целиком.
// Стабильная — local-voice.ts: слух и голос браузерные, думает наш
// текстовый каскад. Звучит проще, зато не зависит от голосового
// провайдера вовсе.
//
// Здесь — только решение «пора ли пересаживаться». Правила:
//   · соединение не поднялось вовсе — падаем на стабильную сразу,
//     человек не должен трижды жать кнопку ради проверки чужого облака;
//   · разговор шёл и оборвался — одиночный обрыв прощаем (сеть в клубе
//     дышит), второй за 30 секунд означает системный сбой провайдера;
//   · часть ошибок переключением не лечится и в счёт не идёт: без
//     микрофона стабильная полоса так же глуха, а бан по оплате или
//     выключенный продукт — не проблема транспорта.

/** Ошибки, при которых менять полосу бессмысленно. */
export const NO_FALLBACK = new Set(["mic-denied", "auth", "disabled", "rate"]);

const WINDOW_MS = 30_000;

export class LaneGuard {
  private fails: number[] = [];

  /** Сообщить о сбое премиальной полосы. Возвращает true, когда пора
   *  переходить на стабильную. everLive — дошёл ли разговор хоть раз
   *  до эфира: сбой на этапе соединения не прощается ни разу. */
  failed(detail: string | undefined, everLive: boolean, now: number): boolean {
    if (NO_FALLBACK.has(detail ?? "")) return false;
    if (!everLive) return true;
    this.fails = this.fails.filter((t) => now - t < WINDOW_MS);
    this.fails.push(now);
    return this.fails.length >= 2;
  }

  reset(): void {
    this.fails = [];
  }
}
