// Дымовая проверка живого продукта.
//
// Все тихие поломки этой недели — один класс: два места, которые обязаны
// говорить одно и то же, разошлись, и ни одно из них не упало. Токен в KV
// против токена на сервере. Отчёт синхронизации против того, что видит
// BRO. База знаний против того, что дошло до модели.
//
// Тесты такое не ловят по своей природе: они гоняются на сборке, где
// прода нет вовсе. Поэтому проверка живёт в самом воркере, читает
// настоящий KV и настоящие настройки и сравнивает пары, которые обычно
// расходятся молча.

/** Итог одной проверки. note пишется для человека: его читают в тревоге,
 *  а не в отладчике, и «qa: 0 из 3 канареек» полезнее, чем false. */
export type Check = { id: string; ok: boolean; note: string };

/** Состояние прошлого прогона. Храним только исход по каждой проверке —
 *  тревога нужна на переходе, а не на каждом повторе. */
export type SmokeState = { at: number; bad: string[] };

export type SmokeDiff = {
  /** Сломалось только что — об этом сообщаем. */
  broke: string[];
  /** Починилось только что — об этом тоже: молчание после тревоги
   *  читается как «всё ещё лежит». */
  fixed: string[];
};

/** Что изменилось со прошлого прогона.
 *
 *  Сравниваем множества, а не количества: три упавшие проверки, одна из
 *  которых сменилась другой, — это событие, хотя число осталось прежним. */
export function diffChecks(prev: SmokeState | null, checks: Check[]): SmokeDiff {
  const bad = checks.filter((c) => !c.ok).map((c) => c.id);
  const was = new Set(prev?.bad ?? []);
  const now = new Set(bad);
  return {
    broke: bad.filter((id) => !was.has(id)),
    // Починенным считаем только то, что раньше падало и сейчас есть в
    // списке проверок: исчезнувшая проверка — не победа, а переименование.
    fixed: [...was].filter((id) => !now.has(id) && checks.some((c) => c.id === id)),
  };
}

/** Текст тревоги для очереди пульта. */
export function smokeText(diff: SmokeDiff, checks: Check[]): string {
  const by = new Map(checks.map((c) => [c.id, c]));
  const lines: string[] = [];
  if (diff.broke.length)
    lines.push(
      `Дым в проде: ${diff.broke.map((id) => `${id} — ${by.get(id)?.note ?? "?"}`).join("; ")}`,
    );
  if (diff.fixed.length) lines.push(`Починилось: ${diff.fixed.join(", ")}.`);
  return lines.join(" ");
}
