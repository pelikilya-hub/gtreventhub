// Рабочий регион: в каком из шести человек живёт.
//
// Продукт перестал быть равен Пхукету, и регион стал верхним фильтром
// на карте, в базе площадок и в аутриче. Карта свой выбор запоминала,
// база — нет: открывал её человек всегда на Пхукете.
//
// Для того, кто работает по всей сети, это мелочь. Для менеджера одного
// региона — клик при каждом заходе, десятки раз в неделю, и каждый раз
// секунда сомнения «я точно в своём регионе или смотрю чужие площадки».
// Самый дорогой вид трения: не мешает, но подтачивает доверие к цифрам
// на экране.
//
// Храним на устройстве, а не в аккаунте. Регион — рабочий контекст, а
// не право: он ничего не открывает и не закрывает, им не управляет
// админ, и человек волен смотреть соседний регион когда захочет.
// Привязка к аккаунту превратила бы удобство в настройку, которую надо
// кому-то выставлять.
//
// Ключ общий с картой: выбрал Самуи на карте — база открылась на Самуи.
// Разные памяти у соседних экранов читаются как сбой, а не как свобода.

const KEY = "gtr-map-view";

type Pref = { region?: string; tag?: string };

const read = (): Pref => {
  try {
    const p = JSON.parse(localStorage.getItem(KEY) ?? "{}") as Pref;
    return p && typeof p === "object" ? p : {};
  } catch {
    // Приватный режим Safari и выключенные куки: выбор просто не
    // переживёт перезагрузку. Это неприятно, но не повод падать.
    return {};
  }
};

/** Регион, в котором человек работал в прошлый раз.
 *
 *  known — список существующих кодов. Проверка не формальность: в
 *  хранилище мог остаться регион, который с тех пор переименовали или
 *  убрали, и тогда экран открылся бы пустым без всякого объяснения. */
export const loadRegion = (known: Record<string, unknown>, fallback = "phuket"): string => {
  const r = read().region;
  return r && known[r] ? r : fallback;
};

export const saveRegion = (region: string): void => {
  try {
    localStorage.setItem(KEY, JSON.stringify({ ...read(), region }));
  } catch {
    /* см. выше: без хранилища просто не запомним */
  }
};

/** Категория площадок на карте. Живёт в том же ключе: она тоже рабочий
 *  контекст, и терять её при перезагрузке так же обидно.
 *
 *  Район сознательно НЕ запоминаем: это выбор на один взгляд, и
 *  застрявший на «Патонге» фильтр читается как поломка карты. */
export const loadTag = (): string | undefined => read().tag;

export const saveTag = (tag: string): void => {
  try {
    localStorage.setItem(KEY, JSON.stringify({ ...read(), tag }));
  } catch {
    /* см. выше */
  }
};
